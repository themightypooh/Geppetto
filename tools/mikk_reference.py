# Regenerate Effigy.Tests/MikkReference.cs: MikkTSpace tangents for the SboxOutputTests fixture.
#
#   blender -b --factory-startup --python tools/mikk_reference.py -- \
#       Effigy.Tests/out/sbox/mikk_fixture.obj Effigy.Tests/MikkReference.cs
#
# Blender's Mesh.calc_tangents() is mikktspace.c (the reference implementation), run on the
# fixture's triangles as ObjWriter wrote them (triangulate on, so Blender sees exactly the triangles
# the bake and the exporters use) and on the file's own normals (OBJ vn, imported as custom normals).
# Axes are imported as written (forward Y, up Z) so the vectors are in Effigy's space.
#
# One Vec4 per loop, polygons in file order: xyz the tangent, w Blender's bitangent sign. Blender's
# v runs up (OBJ), Effigy's down, so the test expects w to be the NEGATIVE of Effigy's.
import sys

import bpy

argv = sys.argv[sys.argv.index("--") + 1:]
src, dst = argv[0], argv[1]

bpy.ops.wm.obj_import(filepath=src, forward_axis="Y", up_axis="Z", validate_meshes=False)
obj = [o for o in bpy.context.selected_objects if o.type == "MESH"][0]  # the import, not the startup cube
mesh = obj.data
mesh.calc_tangents(uvmap=mesh.uv_layers[0].name)

# Which corners Mikk saw welded the way Effigy welds them. Effigy groups corners by (vertex, normal,
# UV) — in file terms (v, vn, vt). Blender stores imported normals compressed, so corners sharing one
# vn can come back ~1e-5 apart, and mikktspace (which welds on exact equality) then splits a group
# Effigy keeps whole. A corner is CLEAN when every corner of its file group has bit-identical normals
# in Blender; only those can be held to a tight tolerance.
faces = [[tuple(int(x) for x in c.split("/")) for c in l.split()[1:]] for l in open(src) if l.startswith("f ")]
groups = {}
for pi, face in enumerate(faces):
    for ci, (v, vt, vn) in enumerate(face):
        groups.setdefault((v, vt, vn), []).append(pi * 3 + ci)
cn = mesh.corner_normals
clean = [False] * len(mesh.loops)
for members in groups.values():
    first = tuple(cn[members[0]].vector)
    ok = all(tuple(cn[m].vector) == first for m in members)
    for m in members:
        clean[m] = ok

lines = []
tris = []
cleans = []
for poly in mesh.polygons:
    tris.append("\t\t" + ", ".join(str(mesh.loops[li].vertex_index) for li in range(poly.loop_start, poly.loop_start + 3)) + ",")
    assert poly.loop_total == 3, "the fixture must arrive triangulated"
    for li in range(poly.loop_start, poly.loop_start + poly.loop_total):
        loop = mesh.loops[li]
        t = loop.tangent
        lines.append(f"\t\tnew( {t.x:.6f}f, {t.y:.6f}f, {t.z:.6f}f, {loop.bitangent_sign:.0f}f ),")
        cleans.append("true" if clean[li] else "false")

with open(dst, "w") as f:
    f.write("namespace Effigy.Tests;\n\n")
    f.write("/// <summary>\n")
    f.write("/// MikkTSpace tangents (Blender " + bpy.app.version_string + " Mesh.calc_tangents, i.e. mikktspace.c) for\n")
    f.write("/// SboxOutputTests.MikkFixture, one per triangle corner in ObjWriter triangulate order.\n")
    f.write("/// Generated by tools/mikk_reference.py; do not edit by hand.\n")
    f.write("/// </summary>\n")
    f.write("internal static class MikkReference\n{\n")
    f.write(f"\t// {len(mesh.polygons)} triangles\n")
    f.write("\tpublic static readonly Vec4[] Tangents =\n\t{\n")
    f.write("\n".join(lines))
    f.write("\n\t};\n\n")
    f.write("\t/// <summary>The vertex indices of each triangle the tangents were taken on, to catch a\n")
    f.write("\t/// triangulation change: if these stop matching, regenerate this file.</summary>\n")
    f.write("\tpublic static readonly int[] Triangles =\n\t{\n")
    f.write("\n".join(tris))
    f.write("\n\t};\n\n")
    f.write("\t/// <summary>Per corner: did Mikk see it welded exactly as Effigy welds it (see the script).</summary>\n")
    f.write("\tpublic static readonly bool[] Clean =\n\t{\n\t\t")
    f.write(", ".join(cleans))
    f.write("\n\t};\n}\n")

print(f"wrote {len(lines)} tangents to {dst}")
