using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Effigy;
using static Effigy.Tests.Report;

namespace Effigy.Tests;

/// <summary>
/// The shape-key pipeline's script and headless ends: a script `export` turns F_MORPH_SUPPORTED on
/// like the editor's Compile, ClipKeys.Morph keys a Morph track (and `effigy key ... morph=` runs
/// it), and `effigy key ... goal` says when its goal keys would do nothing.
/// </summary>
public static class ShapeKeyPipelineTests
{
	public static void Run()
	{
		Section( "shape keys: script export turns morphs on in its materials" );
		TestScriptExportMorphMaterials();
		TestScriptExportStaticSaysDropped();

		Section( "Marionette: keying morph curves headless" );
		TestParseMorph();
		TestMorphKeysRoundTrip();
		TestMorphNotes();
		TestKeyMorphCli();

		Section( "Marionette: key goal warns when nothing would play" );
		TestKeyGoalWarning();
	}

	const string Keyed = "add Primitive name=Sac shape=Sphere radius=10 divisions=10 position=0,0,10\n"
		+ "add ShapeKey key=sac_swell bodies=Sac\n"
		+ "add Stroke bodies=Sac brush=Inflate radius=6 strength=1 points=0,0,20;0,0,19\n"
		+ "add ShapeKeyEnd\n";

	const string EffigyVmat = "// THIS FILE IS AUTO-GENERATED by Effigy\nLayer0\n{\n\tshader \"shaders/complex.shader\"\n\tg_flMetalness \"0\"\n}\n";

	static string TempDir( string what )
	{
		var dir = Path.Combine( Path.GetTempPath(), "effigy-shapekeys", what + "-" + Guid.NewGuid().ToString( "N" )[..6] );
		Directory.CreateDirectory( dir );
		return dir;
	}

	static PartStudio KeyedRiggedStudio( string extra = "" )
	{
		var studio = new PartStudio();
		var r = BuildScript.Run( studio, Keyed + extra );
		var hip = studio.Rig.AddBoneFromPoints( "root", -1, new Vec3( 0, 0, 0 ), new Vec3( 0, 0, 10 ) );
		studio.Rig.AddBoneFromPoints( "top", hip, new Vec3( 0, 0, 10 ), new Vec3( 0, 0, 20 ) );
		return r.Ok ? studio : null;
	}

	static void TestScriptExportMorphMaterials()
	{
		var dir = TempDir( "on" );
		var vmatPath = Path.Combine( dir, "materials/test/sac.vmat" );
		Directory.CreateDirectory( Path.GetDirectoryName( vmatPath ) );
		File.WriteAllText( vmatPath, EffigyVmat );

		var studio = KeyedRiggedStudio( "material 0 materials/test/sac.vmat\n" );
		var r = BuildScript.Run( studio, "export models/test/sac", dir );
		var vmat = File.ReadAllText( vmatPath );
		var dmxPath = Path.Combine( dir, "models/test/sac/sac.dmx" );
		var dmx = File.Exists( dmxPath ) ? File.ReadAllText( dmxPath ) : "";

		Check( "a skinned script export keeps the shape key in the dmx", r.Ok && dmx.Contains( "\"deltaStates\"" ) && dmx.Contains( "\"sac_swell\"" ), r.ToString() );
		Check( "and turns F_MORPH_SUPPORTED on in its Effigy material, under the shader line",
			vmat.Contains( "F_MORPH_SUPPORTED 1" ) && vmat.Contains( "//---- Animation ----" ) && vmat.IndexOf( "F_MORPH" ) > vmat.IndexOf( "shader \"" ) && vmat.Contains( "g_flMetalness \"0\"" ), vmat );
		Check( "and says so", r.Log.Any( l => l.Contains( "materials/test/sac.vmat: F_MORPH_SUPPORTED on" ) ), r.ToString() );

		var again = BuildScript.Run( studio, "export models/test/sac", dir );
		Check( "a second export leaves the flag as it is (once, not twice)", again.Ok && File.ReadAllText( vmatPath ).Split( "F_MORPH_SUPPORTED" ).Length == 2 && !again.Log.Any( l => l.Contains( "F_MORPH_SUPPORTED on" ) ), again.ToString() );

		// A material Effigy did not write is named, never changed.
		var foreignDir = TempDir( "foreign" );
		var foreignPath = Path.Combine( foreignDir, "materials/test/sac.vmat" );
		Directory.CreateDirectory( Path.GetDirectoryName( foreignPath ) );
		const string foreign = "Layer0\n{\n\tshader \"shaders/complex.shader\"\n}\n";
		File.WriteAllText( foreignPath, foreign );
		var rf = BuildScript.Run( KeyedRiggedStudio( "material 0 materials/test/sac.vmat\n" ), "export models/test/sac", foreignDir );
		Check( "a library material is left alone and named", rf.Ok && File.ReadAllText( foreignPath ) == foreign && rf.Log.Any( l => l.Contains( "not an Effigy-written material" ) ), rf.ToString() );

		// No material assigned: nothing on disk to turn on, and the log says how to fix it.
		var rn = BuildScript.Run( KeyedRiggedStudio(), "export models/test/sac", TempDir( "none" ) );
		Check( "a slot with no .vmat says its keys will not show, and how to assign one", rn.Ok && rn.Log.Any( l => l.Contains( "no .vmat file" ) && l.Contains( "material 0" ) ), rn.ToString() );

		// A model without keys touches nothing.
		var plainDir = TempDir( "plain" );
		var plainVmat = Path.Combine( plainDir, "materials/test/box.vmat" );
		Directory.CreateDirectory( Path.GetDirectoryName( plainVmat ) );
		File.WriteAllText( plainVmat, EffigyVmat );
		var plain = new PartStudio();
		BuildScript.Run( plain, "add Primitive name=Box shape=Box sizez=20 position=0,0,10\nmaterial 0 materials/test/box.vmat\n" );
		plain.Rig.AddBoneFromPoints( "root", -1, Vec3.Zero, new Vec3( 0, 0, 20 ) );
		var rp = BuildScript.Run( plain, "export models/test/box", plainDir );
		Check( "a model with no shape keys leaves its materials as written", rp.Ok && File.ReadAllText( plainVmat ) == EffigyVmat, rp.ToString() );

		// The pure step, on its own.
		var mesh = studio.ToMesh();
		var said = VmatMorph.EnableFiles( mesh, s => s == 0 ? "x.vmat" : null, n => null );
		Check( "EnableFiles names a slot it cannot find", said.Count == 1 && said[0].Contains( "slot 0" ), string.Join( " | ", said ) );
		Check( "and does nothing for a mesh without keys", VmatMorph.EnableFiles( new PolyMesh( mesh.Positions, mesh.Faces ), _ => "x.vmat", _ => null ).Count == 0 );
	}

	static void TestScriptExportStaticSaysDropped()
	{
		var r = BuildScript.Run( new PartStudio(), Keyed + "export models/test/sacstatic", TempDir( "static" ) );
		Check( "a static export says it left the shape keys out (OBJ has none)", r.Ok && r.Log.Any( l => l.Contains( "shape key(s)" ) && l.Contains( "left out" ) ), r.ToString() );
	}

	static void TestParseMorph()
	{
		var keys = ClipKeys.ParseMorph( "12:1:EaseOut; 0:0 ;24:0.25", RigEase.Linear, out var error );
		Check( "morph keys parse: frame, weight, ease, sorted by frame", keys is { Count: 3 } && keys[0].Frame == 0 && keys[0].Ease == RigEase.Linear
			&& keys[1].Weight == 1f && keys[1].Ease == RigEase.EaseOut && keys[2].Weight == 0.25f, error );
		Check( "a key that is not frame:weight says the form", ClipKeys.ParseMorph( "3", RigEase.Smooth, out var e1 ) is null && e1.Contains( "frame:weight" ), e1 );
		Check( "a bad ease names the eases", ClipKeys.ParseMorph( "0:1:Bouncy", RigEase.Smooth, out var e2 ) is null && e2.Contains( "Smooth, Linear" ), e2 );
		Check( "a negative frame is refused", ClipKeys.ParseMorph( "-1:1", RigEase.Smooth, out var e3 ) is null && e3 is not null );
		Check( "nothing at all gives an example", ClipKeys.ParseMorph( " ; ", RigEase.Smooth, out var e4 ) is null && e4.Contains( "e.g." ), e4 );
	}

	static void TestMorphKeysRoundTrip()
	{
		var clip = new RigAnimFile { FrameRate = 30, FrameCount = 1 };
		var r = ClipKeys.Morph( clip, "sac_swell", ClipKeys.ParseMorph( "0:0:Linear;12:1:Linear;24:0", RigEase.Smooth, out _ ) );
		var track = clip.Tracks.SingleOrDefault( t => t.Kind == RigTrackKind.Morph );

		Check( "ClipKeys.Morph keys a Morph track named for the shape key", r.Ok && r.Keys == 3 && track?.Name == "sac_swell" && track.Keys.Count == 3, r.ToString() );
		Check( "the weight rides in the key's scale, as Marionette stores it", track is not null && track.Keys[1].Local.Scale.x == 1f && track.Keys[1].Local.Position.Length == 0f );
		Check( "and plays: halfway up at frame 6", MathF.Abs( clip.MorphWeightsAt( 6 )["sac_swell"] - 0.5f ) < 1e-4f, $"{clip.MorphWeightsAt( 6 ).GetValueOrDefault( "sac_swell" )}" );

		ClipKeys.Morph( clip, "sac_swell", ClipKeys.ParseMorph( "12:0.6", RigEase.Linear, out _ ) );
		Check( "keying a frame again replaces its key", track.Keys.Count == 3 && MathF.Abs( clip.MorphWeightsAt( 12 )["sac_swell"] - 0.6f ) < 1e-5f );

		var json = RigAnimWriter.Write( clip );
		var back = RigAnimFile.Read( json );
		var t2 = back.Tracks.SingleOrDefault( t => t.Kind == RigTrackKind.Morph && t.Name == "sac_swell" );
		Check( "it round-trips through the .riganim writer and reader", json.Contains( "\"Morph\"" ) && t2 is { Keys.Count: 3 }
			&& t2.Keys.Select( k => k.Frame ).SequenceEqual( new[] { 0, 12, 24 } ) && t2.Keys[0].Ease == RigEase.Linear && t2.Keys[2].Ease == RigEase.Smooth
			&& Enumerable.Range( 0, 25 ).All( f => MathF.Abs( back.MorphWeightsAt( f )["sac_swell"] - clip.MorphWeightsAt( f )["sac_swell"] ) < 1e-5f ) );
		Check( "and the file's length covers the keys", back.FrameCount >= 25, $"{back.FrameCount}" );

		var s = new Skeleton();
		s.AddBone( "root", -1, Xform.Identity );
		var dmx = DmxAnimWriter.Write( s, back.ToClip( s ) );
		Check( "the baked export writes it as a flex channel", dmx.Contains( "\"sac_swell_flex_channel\"" ) );
	}

	static void TestMorphNotes()
	{
		var clip = new RigAnimFile { FrameRate = 30 };
		clip.MorphEvents.Add( new RigMorphEvent { Morph = "gape", Start = 10, End = 20 } );

		Check( "an empty name is refused", ClipKeys.Morph( clip, " ", ClipKeys.ParseMorph( "0:1", RigEase.Smooth, out _ ) ).Error?.Contains( "morph=" ) == true );
		Check( "a name with a space is refused (no shape key has one)", ClipKeys.Morph( clip, "big gape", ClipKeys.ParseMorph( "0:1", RigEase.Smooth, out _ ) ).Error?.Contains( "spaces" ) == true );
		Check( "and neither keyed anything", clip.Tracks.Count == 0 );

		var r = ClipKeys.Morph( clip, "gape", ClipKeys.ParseMorph( "0:0;15:1.5", RigEase.Smooth, out _ ), new[] { "gape", "blink" } );
		Check( "a weight outside 0-1 is keyed but said", r.Ok && r.Notes.Any( n => n.Contains( "1.5" ) && n.Contains( "outside 0-1" ) ), r.ToString() );
		Check( "a morph event over the same frames is said to override them", r.Notes.Any( n => n.Contains( "morph event" ) && n.Contains( "10-20" ) ), r.ToString() );
		Check( "a name the model has gives no do-nothing warning", !r.Notes.Any( n => n.Contains( "do nothing" ) ) );

		var missing = ClipKeys.Morph( clip, "gaep", ClipKeys.ParseMorph( "0:1", RigEase.Smooth, out _ ), new[] { "gape", "blink" } );
		Check( "a name the model lacks warns that the keys do nothing, listing what it has", missing.Ok && missing.Notes.Any( n => n.Contains( "no shape key 'gaep'" ) && n.Contains( "gape, blink" ) && n.Contains( "do nothing" ) ), missing.ToString() );
	}

	/// <summary>Run the CLI with stdout and stderr captured.</summary>
	static (int Code, string Out, string Err) Cli( params string[] args )
	{
		var (oldOut, oldErr) = (Console.Out, Console.Error);
		var (o, e) = (new StringWriter(), new StringWriter());

		try
		{
			Console.SetOut( o );
			Console.SetError( e );
			return (MarionetteCli.Key( args ), o.ToString(), e.ToString());
		}
		catch ( Exception ex )
		{
			return (-1, o.ToString(), e + ex.ToString());
		}
		finally
		{
			Console.SetOut( oldOut );
			Console.SetError( oldErr );
		}
	}

	const string ClipJson = "{\"SourceModel\":\"models/test/sac.vmdl\",\"RigAsset\":\"\",\"AnimationSpeed\":30,\"FrameCount\":10,"
		+ "\"BoneTracks\":[],\"Marks\":[{\"Name\":\"keep\",\"Frame\":3}],"
		+ "\"MorphEvents\":[{\"Name\":\"blink\",\"MorphName\":\"\",\"StartFrame\":40,\"EndFrame\":44,\"Value\":1}]}";

	static void TestKeyMorphCli()
	{
		var dir = TempDir( "cli" );
		var path = Path.Combine( dir, "sac.riganim" );
		File.WriteAllText( path, ClipJson );

		var (code, output, err) = Cli( "key", path, "morph=sac_swell", "0:0;15:1:EaseOut;30:0", "shapes=sac_swell,blink", "ease=Linear" );
		var back = RigAnimFile.Read( File.ReadAllText( path ) );
		var track = back.Tracks.SingleOrDefault( t => t.Kind == RigTrackKind.Morph );
		Check( "effigy key clip morph=Name keys the curve and writes the clip", code == 0 && output.Contains( "3 key(s)" ) && track?.Name == "sac_swell" && track.Keys.Count == 3
			&& track.Keys[0].Ease == RigEase.Linear && track.Keys[1].Ease == RigEase.EaseOut && MathF.Abs( back.MorphWeightsAt( 15 )["sac_swell"] - 1f ) < 1e-5f, $"{code} {output} {err}" );
		Check( "with a name the model has, it warns nothing", !err.Contains( "warning" ), err );

		var text = File.ReadAllText( path );
		Check( "and keeps the rest of the clip (marks, morph events)", text.Contains( "\"keep\"" ) && back.MorphEvents.Any( m => m.Morph == "blink" ), text );

		var (code2, _, err2) = Cli( "key", path, "morph=sac_swel", "5:1", "shapes=sac_swell,blink" );
		Check( "a misspelt shape key is keyed but warned about", code2 == 0 && err2.Contains( "warning:" ) && err2.Contains( "no shape key 'sac_swel'" ), err2 );

		var (code3, _, err3) = Cli( "key", path, "morph=sac_swell", "5:1" );
		Check( "without shapes= it says the name was not checked", code3 == 0 && err3.Contains( "not checked" ), err3 );

		var before = File.ReadAllText( path );
		var (code4, _, err4) = Cli( "key", path, "morph=sac_swell", "5" );
		Check( "bad keys fail, say the form, and leave the file alone", code4 == 1 && err4.Contains( "frame:weight" ) && File.ReadAllText( path ) == before, err4 );

		var (code5, _, err5) = Cli( "key", path, "morph=sac_swell", "5:1", "rig=x.ctrlrig" );
		Check( "an option morph keying does not take is refused, not ignored", code5 == 1 && err5.Contains( "rig=x.ctrlrig" ), err5 );

		var outPath = Path.Combine( dir, "copy.riganim" );
		var (code6, _, _) = Cli( "key", path, "morph=gape", "0:1", $"write={outPath}" );
		Check( "write= saves elsewhere and leaves the source as it was", code6 == 0 && File.Exists( outPath ) && File.ReadAllText( path ) == before
			&& RigAnimFile.Read( File.ReadAllText( outPath ) ).Tracks.Any( t => t.Kind == RigTrackKind.Morph && t.Name == "gape" ) );
	}

	static void TestKeyGoalWarning()
	{
		// A clip that names its rig, found upward from the clip's folder the way Marionette's
		// project lays them out (Assets/animations/...).
		var dir = TempDir( "goal" );
		var animations = Path.Combine( dir, "Assets", "animations" );
		Directory.CreateDirectory( animations );
		File.WriteAllText( Path.Combine( animations, "arms.ctrlrig" ),
			"{\"IkConstraints\":[{\"Name\":\"right\",\"TargetBone\":\"cable1_hand\",\"ChainLength\":4,\"Live\":true,\"Enabled\":true}]}" );

		var clipJson = "{\"SourceModel\":\"\",\"RigAsset\":\"animations/arms.ctrlrig\",\"AnimationSpeed\":30,\"FrameCount\":30,\"BoneTracks\":[]}";
		var clipPath = Path.Combine( animations, "reach.riganim" );
		File.WriteAllText( clipPath, clipJson );

		var (code, _, err) = Cli( "key", clipPath, "cable0_hand", "goal", "0:10,0,40;20:10,0,50" );
		Check( "key goal on a bone no live IK constraint ends at prints the warning", code == 0 && err.Contains( "warning: no live IK constraint ends at cable0_hand" ) && err.Contains( "do nothing" ), err );
		Check( "and still writes the goal keys", RigAnimFile.Read( File.ReadAllText( clipPath ) ).IkGoalTracks.Any( t => t.Name == "cable0_hand" && t.Keys.Count == 2 ) );

		File.WriteAllText( clipPath, clipJson );
		var (code2, output2, err2) = Cli( "key", clipPath, "cable1_hand", "goal", "0:10,0,40" );
		Check( "on the bone the rig's live constraint ends at, it warns nothing", code2 == 0 && !err2.Contains( "warning" ) && output2.Contains( "1 key(s)" ), err2 );

		// The constraint there but not live: baked IK does not play goal keys.
		File.WriteAllText( Path.Combine( animations, "arms.ctrlrig" ),
			"{\"IkConstraints\":[{\"Name\":\"right\",\"TargetBone\":\"cable1_hand\",\"ChainLength\":4,\"Live\":false,\"Enabled\":true}]}" );
		File.WriteAllText( clipPath, clipJson );
		var (_, _, err3) = Cli( "key", clipPath, "cable1_hand", "goal", "0:10,0,40" );
		Check( "a constraint that is not live warns too", err3.Contains( "warning: no live IK constraint ends at cable1_hand" ), err3 );

		// No rig to be found: it cannot check, and says the keys may do nothing.
		var lone = Path.Combine( TempDir( "lone" ), "reach.riganim" );
		File.WriteAllText( lone, clipJson.Replace( "animations/arms.ctrlrig", "animations/missing.ctrlrig" ) );
		var (code4, _, err4) = Cli( "key", lone, "cable0_hand", "goal", "0:10,0,40" );
		Check( "with the rig not found it warns that it could not check", code4 == 0 && err4.Contains( "warning:" ) && err4.Contains( "was not found" ), err4 );
	}
}
